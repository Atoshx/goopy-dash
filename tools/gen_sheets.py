# Generates src/generated/Sheets.hpp from sheets/*.json: one struct per row.
import json, os
root = os.path.join(os.path.dirname(__file__), '..')
S = {n: json.load(open(os.path.join(root, 'sheets', n + '.json'))) for n in ['animations', 'sounds', 'attacks', 'boss']}
def s(v): return 'nullptr' if v is None else json.dumps(v)
def f(v): return repr(float(v)) + 'f'
out = ['// Generated by tools/gen_sheets.py from sheets/*.json. Edit the sheets, not this file.', '#pragma once',
       '#include <array>', '#include <string_view>', 'namespace goopy::sheets {', '']
out += ['struct Anim { std::string_view id; std::string_view prefix; int frames; float fps; bool loop; };',
        f'inline constexpr std::array<Anim, {len(S["animations"]["rows"])}> kAnims = {{{{']
out += [f'    Anim{{{s(r["id"])}, {s(r["spritePrefix"])}, {r["frameCount"]}, {f(r["fps"])}, {str(r["loop"]).lower()}}},' for r in S['animations']['rows']]
out += ['}};', '']
maxc = max(len(r['clipNames']) for r in S['sounds']['rows'])
out += [f'struct Sound {{ std::string_view id; std::array<std::string_view, {maxc}> clips; int clipCount; float volume; }};',
        f'inline constexpr std::array<Sound, {len(S["sounds"]["rows"])}> kSounds = {{{{']
for r in S['sounds']['rows']:
    clips = ', '.join(s(c) for c in r['clipNames']) 
    out.append(f'    Sound{{{s(r["id"])}, {{{clips}}}, {len(r["clipNames"])}, {f(r["volume"])}}},')
out += ['}};', '']
out += ['struct Attack { std::string_view id; std::string_view windupAnim; float windupSec; const char* sound; const char* voice; const char* hazardAnim; float hazardScale; float hazardFootPx; float hazardWidth; float hazardHeight; float hazardSpeed; int weight; };',
        f'inline constexpr std::array<Attack, {len(S["attacks"]["rows"])}> kAttacks = {{{{']
for r in S['attacks']['rows']:
    out.append(f'    Attack{{{s(r["id"])}, {s(r["windupAnim"])}, {f(r["windupSec"])}, {s(r["sound"])}, {s(r["voice"])}, {s(r["hazardAnim"])}, {f(r["hazardScale"] or 0)}, {f(r["hazardFootPx"] or 0)}, {f(r["hazardWidth"])}, {f(r["hazardHeight"])}, {f(r["hazardSpeed"])}, {r["weight"]}}},')
out += ['}};', '']
for r in S['boss']['rows']:
    if isinstance(r['value'], (int, float)):
        out.append(f'inline constexpr float k{r["id"][0].upper() + r["id"][1:]} = {float(r["value"])}f; // {r["unit"]}')
out += ['', '} // namespace goopy::sheets', '']
os.makedirs(os.path.join(root, 'src', 'generated'), exist_ok=True)
open(os.path.join(root, 'src', 'generated', 'Sheets.hpp'), 'w').write('\n'.join(out))
print('generated', sum(len(v['rows']) for v in S.values()), 'rows')
